-- Esquema completo de la base (PostgreSQL 15 o superior): 9 tablas.
--
-- Reemplaza a los scripts de Oracle (bigbang.sql, empresas_revision.sql,
-- indices_empresas.sql, noticias.sql), que se fueron aplicando de a uno sobre
-- la base; esa versión quedó en el tag `oracle-final` de git. Las tablas
-- eventos y postulaciones no tenían script: se pasaron tal como estaban en
-- la base Oracle del proyecto.
--
-- Orden: correr este archivo y después insert_geografia.sql. Se corre contra
-- la base ya creada (en Railway la da el servicio PostgreSQL; en local, la
-- que levanta docker compose). No crea usuarios ni bases.

-- 0 usuario, 1 administrador
CREATE TABLE representates (
    id_representante          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_representante      VARCHAR(150) NOT NULL,
    apellido_representante    VARCHAR(150) NOT NULL,
    email_representante       VARCHAR(150) NOT NULL CONSTRAINT uq_email_representante UNIQUE,
    contrasenia_representate  VARCHAR(256) NOT NULL,
    n_telefono_representante  VARCHAR(22),
    fecha_de_creacion         TIMESTAMP,
    rol                       SMALLINT DEFAULT 0,
    -- 1 activo, 0 dado de baja (baja lógica desde el dashboard admin)
    estado                    SMALLINT
);

-- Geografía de Córdoba (se carga con insert_geografia.sql)
CREATE TABLE zonas (
    id_zona      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_zona  VARCHAR(250)
);

CREATE TABLE departamentos (
    id_departamento      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_departamento  VARCHAR(250),
    id_zona              INTEGER NOT NULL CONSTRAINT fk_deptos_zonas REFERENCES zonas (id_zona)
);

CREATE TABLE localidades (
    id_localidad      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_localidad  VARCHAR(250),
    id_departamento   INTEGER NOT NULL CONSTRAINT fk_localidades_deptos REFERENCES departamentos (id_departamento)
);

-- Imágenes subidas (noticias y productos). Se guardan en la base para que
-- queden en el mismo volumen que el resto de los datos: el backend no
-- necesita disco propio. El backend las sirve en GET /api/v1/imagenes/{id}.
-- Una imagen no se modifica: reemplazarla crea otra fila con otro id.
CREATE TABLE imagenes (
    id_imagen   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contenido   BYTEA NOT NULL,
    tipo_mime   VARCHAR(50) NOT NULL,
    creada      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Empresas: cuit y razón social son columnas propias; el resto del perfil
-- público (nombre, rubro, ubicación, redes y productos) vive en el documento
-- datos_publico (ver empresas.json y backend/api/v1/schemas/empresas.py).
CREATE TABLE empresas (
    id_empresa        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cuit              BIGINT NOT NULL CONSTRAINT uq_empresas_cuit UNIQUE,
    razon_social      VARCHAR(255) NOT NULL,
    datos_publico     JSONB,
    id_representante  INTEGER CONSTRAINT fk_empresas_representante REFERENCES representates (id_representante),
    -- 0 pendiente (no visible en la vidriera pública), 1 aprobada, 2 rechazada (ver motivo_rechazo)
    estado            SMALLINT NOT NULL DEFAULT 0,
    motivo_rechazo    VARCHAR(500),
    -- Copias de campos del documento para filtrar con índice (buscador del
    -- admin y mapa público). Las calcula la base: no se escriben a mano.
    rubro_vc          TEXT GENERATED ALWAYS AS (datos_publico ->> 'rubro') STORED,
    zona_vc           TEXT GENERATED ALWAYS AS (datos_publico -> 'ubicacion' ->> 'zona') STORED,
    departamento_vc   TEXT GENERATED ALWAYS AS (datos_publico -> 'ubicacion' ->> 'departamento') STORED,
    -- Forma mínima del documento, validada también por la base (el backend
    -- la valida antes con Pydantic): campos obligatorios, coordenadas en
    -- rango y nombre en cada producto.
    CONSTRAINT ck_empresas_documento CHECK (
        datos_publico IS NULL OR (
            datos_publico ?& ARRAY['nombre_empresa', 'rubro', 'ubicacion', 'descripcion', 'correo_empresa']
            AND jsonb_typeof(datos_publico -> 'ubicacion' -> 'latitud') = 'number'
            AND jsonb_typeof(datos_publico -> 'ubicacion' -> 'longitud') = 'number'
            AND (datos_publico -> 'ubicacion' ->> 'latitud')::numeric BETWEEN -90 AND 90
            AND (datos_publico -> 'ubicacion' ->> 'longitud')::numeric BETWEEN -180 AND 180
            AND NOT jsonb_path_exists(datos_publico, '$.productos.* ? (!exists(@.nombre))')
        )
    )
);

-- El dashboard admin siempre arranca filtrando por pendientes.
CREATE INDEX idx_empresas_estado ON empresas (estado);
CREATE INDEX idx_empresas_rubro ON empresas (rubro_vc);
CREATE INDEX idx_empresas_zona ON empresas (zona_vc);
CREATE INDEX idx_empresas_departamento ON empresas (departamento_vc);
-- Filtro típico "departamento X y rubro Y"
CREATE INDEX idx_empresas_depto_rubro ON empresas (departamento_vc, rubro_vc);

-- Noticias (la imagen de portada, si tiene, está en la tabla imagenes).
CREATE TABLE noticias (
    id_noticia              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo                  VARCHAR(200) NOT NULL,
    cuerpo                  TEXT NOT NULL,
    id_imagen               INTEGER CONSTRAINT fk_noticias_imagen REFERENCES imagenes (id_imagen),
    fecha_creacion          TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_actualizacion     TIMESTAMP,
    id_representante_autor  INTEGER CONSTRAINT fk_noticias_autor REFERENCES representates (id_representante),
    -- 1 publicada, 0 dada de baja
    estado                  SMALLINT NOT NULL DEFAULT 1
);

-- El listado público ordena por fecha descendente.
CREATE INDEX idx_noticias_fecha ON noticias (fecha_creacion DESC);

-- Eventos (calendario y dashboard admin). fecha va como texto 'AAAA-MM-DD',
-- igual que en Oracle, porque así la manda y la lee el frontend.
CREATE TABLE eventos (
    id_evento    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha        VARCHAR(10) NOT NULL,
    titulo       VARCHAR(250) NOT NULL,
    descripcion  TEXT,
    hora         VARCHAR(100),
    lugar        VARCHAR(250),
    color        VARCHAR(20) NOT NULL DEFAULT 'blue'
);

-- Postulaciones de empresas a eventos (una por empresa y evento).
CREATE TABLE postulaciones (
    id_postulacion     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_empresa         INTEGER NOT NULL CONSTRAINT fk_postulacion_empresa REFERENCES empresas (id_empresa),
    id_evento          INTEGER NOT NULL CONSTRAINT fk_postulacion_evento REFERENCES eventos (id_evento),
    fecha_postulacion  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    estado             VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE',
    motivo_rechazo     VARCHAR(500),
    CONSTRAINT uq_empresa_evento UNIQUE (id_empresa, id_evento)
);
